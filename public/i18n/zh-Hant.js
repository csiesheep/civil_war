export function t(path, vars) {
  let v = T;
  for (const k of String(path).split(".")) { v = v == null ? undefined : v[k]; }
  if (typeof v !== "string") return String(path);
  return vars ? v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k]))) : v;
}
